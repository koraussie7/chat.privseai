/** Kilo free-tier key shape: a compact JWS/JWT (three dot-separated b64 parts). */
export function looksLikeKiloKey(key: string): boolean {
	const k = key.trim();
	if (!/^[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$/.test(k)) return false;
	if (k.length < 80 || k.length > 1200) return false;
	return true;
}

/** Cheap JWT payload read for an expiry hint (no verification — UX hint only). */
export function kiloKeyExpiryHint(key: string): string | null {
	try {
		const payload = JSON.parse(atob(key.split(".")[1].replace(/-/g, "+").replace(/_/g, "/")));
		if (typeof payload.exp !== "number") return null;
		const ms = payload.exp * 1000;
		const years = (ms - Date.now()) / (365.25 * 24 * 3600 * 1000);
		return years > 0 ? `약 ${years.toFixed(1)}년 후 만료` : "이미 만료됨";
	} catch {
		return null;
	}
}

export interface ProvisionConfig {
	kiloKey: string;
	/** optional additional free-tier keys the user also has */
	groqKey?: string;
	/** state dir: isolated profile by default */
	stateDir?: string;
}

/**
 * Build the one-shot provisioning shell script the user runs ONCE after
 * installing bitterbot. Their key goes into THEIR LaunchAgent plist and
 * config — nothing is sent anywhere.
 */
export function buildProvisionScript(cfg: ProvisionConfig): string {
	const state = cfg.stateDir ?? "$HOME/.bitterbot-isolated";
	return `#!/bin/zsh
# PrivseAI × bitterbot provisioning (generated by privseai.com)
# Your API key is written only to your own machine — never sent anywhere.
set -euo pipefail

STATE_DIR="${state}"
CONFIG="$STATE_DIR/bitterbot.json"
PLISTD="$HOME/Library/LaunchAgents"
PLIST="$HOME/Library/LaunchAgents/ai.bitterbot.gateway.plist"

mkdir -p "$STATE_DIR/identity"

# 1) Ensure the Kilo provider exists in config with the user's key.
python3 - "$CONFIG" <<PYEOF
import json, os, sys
p = sys.argv[1]
c = json.load(open(p)) if os.path.exists(p) else {"models": {"providers": {}}, "agents": {"defaults": {"model": {}}}}
prov = c.setdefault("models", {}).setdefault("providers", {})
kilo = prov.setdefault("kilocode", {
    "baseUrl": "https://api.kilo.ai/api/gateway/",
    "api": "openai-completions",
    "apiKey": "\${KILOCODE_API_KEY}",
    "models": [{"id": "kilo-auto/free", "name": "Kilo Auto (free tier)"}],
})
kilo["apiKey"] = "\${KILOCODE_API_KEY}"
if not any(m.get("id") == "kilo-auto/free" for m in kilo.get("models", [])):
    kilo.setdefault("models", []).append({"id": "kilo-auto/free", "name": "Kilo Auto (free tier)"})
m = c["agents"]["defaults"].setdefault("model", {})
m["primary"] = "kilocode/kilo-auto/free"
fb = m.setdefault("fallbacks", [])
for extra in ("groq/openai/gpt-oss-120b", "ovh-ai/Mistral-Small-3.2-24B-Instruct-2506", "pollinations/openai-fast"):
    if extra not in fb:
        fb.append(extra)
json.dump(c, open(p, "w"), indent=2, ensure_ascii=False)
print("config written:", p)
PYEOF
${
	cfg.groqKey
		? `# user-supplied Groq key (optional)
/usr/libexec/PlistBuddy -c "Add :EnvironmentVariables:GROQ_API_KEY string ${cfg.groqKey}" "$PLIST" 2>/dev/null || \\
  /usr/libexec/PlistBuddy -c "Set :EnvironmentVariables:GROQ_API_KEY ${cfg.groqKey}" "$PLIST" || true
`
		: ""
}
# 2) Put the key in the gateway environment (macOS LaunchAgent).
KILO_KEY="\${KILO_KEY:?export KILOCODE_API_KEY first or inline: KILO_KEY=... ./provision.sh}"
if [[ "$(uname)" == "Darwin" ]]; then
  mkdir -p "$(dirname "$PLIST")"
  /usr/libexec/PlistBuddy -c "Add :EnvironmentVariables:KILOCODE_API_KEY string $KILO_KEY" "$PLIST" 2>/dev/null || \\
    /usr/libexec/PlistBuddy -c "Set :EnvironmentVariables:KILOCODE_API_KEY $KILO_KEY" "$PLIST"
fi

# 3) Import the companion seed produced by privseai.com (if provided).
#    Usage: ./provision.sh path/to/<companion>.bitterbot-seed.json
if [[ -n "\${1:-}" && -f "$1" ]]; then
  python3 - "$1" "$STATE_DIR" <<'PY2'
import json, os, sys, shutil
seed_path, state = sys.argv[1], sys.argv[2]
seed = json.load(open(seed_path))
assert seed.get("format") == "privseai-bitterbot-seed", "not a privseai seed"
for key in ("genomeFilename", "memoryFilename"):
    rel = seed["files"][key]
    assert ".." not in rel, "unsafe path"
    dst = os.path.join(state, rel)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    body = seed["genome" if "GENOME" in key else "memory"]
    import pathlib
    pathlib.Path(dst).write_text(body)
    print("seeded:", dst)
PY2
fi

# 4) Restart the gateway if it is installed as a LaunchAgent.
launchctl bootout "gui/$(id -u)/ai.bitterbot.gateway" 2>/dev/null || true
sleep 2
launchctl bootstrap "gui/$(id -u)" "$PLIST" 2>/dev/null && echo "gateway restarted" || echo "gateway not installed yet — start it after first onboarding run"

echo "Done. Keep your key private."
`;
}

/** Persist the seed + script as downloads (browser helper). */
export function downloadFile(filename: string, content: string, mime = "application/json"): void {
	const blob = new Blob([content], { type: mime });
	const url = URL.createObjectURL(blob);
	const a = document.createElement("a");
	a.href = url;
	a.download = filename;
	a.click();
	URL.revokeObjectURL(url);
}
