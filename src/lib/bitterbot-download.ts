export type BitterbotOs = "macos-arm" | "macos-x64" | "linux" | "windows" | "unknown";

/** Best-effort OS detection from the browser UA (download button routing). */
export function detectBitterbotOs(): BitterbotOs {
	if (typeof navigator === "undefined") return "unknown";
	const ua = navigator.userAgent;
	if (/Mac/.test(ua)) {
		// Apple Silicon ships ARM in the UA on modern Safari/Chrome.
		return /arm|aarch64/i.test(navigator.platform ?? "") || /arm64/.test(ua)
			? "macos-arm"
			: "macos-x64";
	}
	if (/Linux/.test(ua)) return "linux";
	if (/Win/.test(ua)) return "windows";
	return "unknown";
}

